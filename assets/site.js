// 4. PUBLICATION RENDERING
// ============================================================

function renderPublications(publications, container) {

  if (!container) return;

  container.innerHTML = "";

  if (publications.length === 0) {

    container.innerHTML = `
      <article class="content-card">
        <p>No publications match your search.</p>
      </article>
    `;

    return;
  }


  publications.forEach((publication) => {

    const article = document.createElement("article");

    article.className = "content-card publication-card";


    let linkHTML = "";

    if (publication.doi) {

      linkHTML = `
        <p>
          <a
            href="${publication.doi}"
            target="_blank"
            rel="noreferrer">
            DOI / Publication
          </a>
        </p>
      `;
    }


    let detailsHTML = "";

    if (publication.details) {

      detailsHTML = `
        <p>${publication.details}</p>
      `;
    }


    article.innerHTML = `

      <p class="eyebrow">
        ${publication.type} · ${publication.year}
      </p>

      <h3>
        ${publication.title}
      </h3>

      <p>
        ${publication.authors}
      </p>

      <p>
        <strong>${publication.venue}</strong>
      </p>

      ${detailsHTML}

      ${linkHTML}

    `;


    container.appendChild(article);

  });

}



