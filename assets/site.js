// 6. PUBLICATION SEARCH
// ============================================================

const publicationSearch =
  document.getElementById("publication-search");


if (publicationSearch) {

  publicationSearch.addEventListener("input", () => {

    const query =
      publicationSearch.value
        .toLowerCase()
        .trim();


    const activeTab =
      document.querySelector(".tab.active");


    const activeType =
      activeTab
        ? activeTab.dataset.tab
        : "full";


    const source =
      activeType === "preprints"
        ? preprints
        : fullPublications;


    const filtered =
      source.filter((publication) => {

        const searchableText = `

          ${publication.type}
          ${publication.year}
          ${publication.title}
          ${publication.authors}
          ${publication.venue}
          ${publication.details}

        `.toLowerCase();


        return searchableText.includes(query);

      });


    if (activeType === "preprints") {

      renderPublications(
        filtered,
        preprintPublicationContainer
      );

    } else {

      renderPublications(
        filtered,
        fullPublicationContainer
      );

    }

  });

}



