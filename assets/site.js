// 12. NEURAL / NETWORK BACKGROUND
// ============================================================

const canvas =
  document.getElementById(
    "neural-canvas"
  );


if (canvas) {

  const ctx =
    canvas.getContext("2d");


  let width;
  let height;


  let particles = [];


  const mouse = {

    x: null,
    y: null

  };



  function resizeCanvas() {

    width =
      canvas.width =
      window.innerWidth;


    height =
      canvas.height =
      window.innerHeight;


    createParticles();

  }



  function createParticles() {

    particles = [];


    let particleCount =
      Math.floor(
        (width * height) / 18000
      );


    particleCount =
      Math.min(
        particleCount,
        100
      );


    for (
      let i = 0;
      i < particleCount;
      i++
    ) {

      particles.push({

        x:
          Math.random() * width,

        y:
          Math.random() * height,

        vx:
          (Math.random() - 0.5) * 0.25,

        vy:
          (Math.random() - 0.5) * 0.25,

        radius:
          Math.random() * 1.5 + 0.7

      });

    }

  }



  function drawParticle(particle) {

    ctx.beginPath();

    ctx.arc(
      particle.x,
      particle.y,
      particle.radius,
      0,
      Math.PI * 2
    );


    ctx.fillStyle =
      "rgba(105,230,255,0.65)";


    ctx.fill();

  }



  function drawConnections() {

    for (
      let i = 0;
      i < particles.length;
      i++
    ) {

      for (
        let j = i + 1;
        j < particles.length;
        j++
      ) {

        const dx =
          particles[i].x -
          particles[j].x;


        const dy =
          particles[i].y -
          particles[j].y;


        const distance =
          Math.sqrt(
            dx * dx +
            dy * dy
          );


        if (distance < 145) {

          const opacity =
            (1 - distance / 145) *
            0.20;


          ctx.beginPath();


          ctx.moveTo(
            particles[i].x,
            particles[i].y
          );


          ctx.lineTo(
            particles[j].x,
            particles[j].y
          );


          ctx.strokeStyle =
            `rgba(105,230,255,${opacity})`;


          ctx.lineWidth =
            0.8;


          ctx.stroke();

        }

      }

    }

  }



  function updateParticles() {

    particles.forEach(
      (particle) => {

        particle.x +=
          particle.vx;


        particle.y +=
          particle.vy;


        if (
          particle.x < 0 ||
          particle.x > width
        ) {

          particle.vx *= -1;

        }


        if (
          particle.y < 0 ||
          particle.y > height
        ) {

          particle.vy *= -1;

        }



        if (
          mouse.x !== null &&
          mouse.y !== null
        ) {

          const dx =
            mouse.x -
            particle.x;


          const dy =
            mouse.y -
            particle.y;


          const distance =
            Math.sqrt(
              dx * dx +
              dy * dy
            );


          if (distance < 120) {

            particle.x -=
              dx * 0.0015;


            particle.y -=
              dy * 0.0015;

          }

        }

      }
    );

  }



  function animate() {

    ctx.clearRect(
      0,
      0,
      width,
      height
    );


    updateParticles();


    drawConnections();


    particles.forEach(
      drawParticle
    );


    requestAnimationFrame(
      animate
    );

  }



  window.addEventListener(
    "resize",
    resizeCanvas
  );



  window.addEventListener(
    "mousemove",
    (event) => {

      mouse.x =
        event.clientX;


      mouse.y =
        event.clientY;

    }
  );



  window.addEventListener(
    "mouseout",
    () => {

      mouse.x =
        null;


      mouse.y =
        null;

    }
  );



  resizeCanvas();

  animate();

}
